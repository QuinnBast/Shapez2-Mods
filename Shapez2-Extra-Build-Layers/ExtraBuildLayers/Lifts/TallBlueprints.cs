using System;
using System.Collections.Generic;
using Game.Core.BuildingLogic.Data;
using Game.Core.Coordinates;
using Game.Core.Rendering.MeshGeneration;
using Unity.Mathematics;
using ILogger = Core.Logging.ILogger;

namespace QuinnBast.Shapez2.ExtraBuildLayers;

/// <summary>
/// Gives a tall lift or pipe a placement preview as tall as the building it places.
///
/// A placed tall piece draws its full height: <see cref="TallShaft"/> stacks extra bodies above
/// the one the chunk drawer puts down. The **preview** never goes near that code. A building
/// being placed is drawn by <c>SmartBuildingBlueprintRenderer.Draw</c>, which takes
/// <c>IBuildingDrawData.IsolatedBlueprintMesh</c> and nothing else - and
/// <c>BuildingMeshGenerator.GenerateIsolatedBlueprintMesh</c> builds that from
/// <c>mainMeshPerLayer[0]</c> plus glass, one body. A stretched definition copied the stock
/// lift's draw data, so its preview was the stock two-layer one however tall the lift was.
///
/// (<c>IBuildingDrawData.PreviewMesh</c> looks like the field to fix and is not: nothing in the
/// game reads it.)
///
/// So each stretched definition gets its own draw data with a blueprint mesh baked once at load,
/// laid out by <see cref="TallShaft"/> so preview and building cannot disagree. Its
/// <c>CombinedBlueprintMesh</c> - the mass-selection outline, which adds belt and pipe end caps
/// at the connectors - is regenerated by the game's own
/// <c>BuildingMeshGenerator.GenerateFullBlueprintMesh</c>, so the caps land on the stretched
/// connectors rather than two layers up.
/// </summary>
internal static class TallBlueprints
{
    /// <summary><c>GenerateIsolatedBlueprintMesh</c> builds exactly this many LODs.</summary>
    private const int BlueprintLods = 4;

    /// <summary><c>MeshBuilder</c> accepts LODs 0 to 5; a main mesh has at most that many.</summary>
    private const int MainLods = 6;

    /// <summary>
    /// Definitions whose static mesh already carries the whole shaft. <see cref="TallShaft.Draw"/>
    /// skips these, or the shaft would be drawn twice.
    /// </summary>
    internal static readonly HashSet<BuildingDefinitionId> StaticallyStacked = new HashSet<BuildingDefinitionId>();

    private static int Stacked;
    private static int Failed;

    public static IBuildingDrawData WithStackedBlueprint(
        BuildingDefinitionId id,
        IBuildingDrawData existing,
        ILODMesh single,
        int span,
        IBuildingConnectorData connectors,
        IMeshCache meshCache,
        VisualThemeBaseResources theme,
        ILogger logger)
    {
        ILODMesh body = existing.MainMeshPerLayer is { Length: > 0 } ? existing.MainMeshPerLayer[0] : null;
        if (body == null || existing.IsolatedBlueprintMesh == null || meshCache == null ||
            TallShaft.ExtraBodies(span) == 0 && !TallShaft.NeedsCap(span))
        {
            return existing;
        }

        // Read off the stretched connectors, the same tile bounds TallShaft.Direction reads off
        // the finished definition.
        int direction = connectors.TileBounds.Min.z < 0 ? -1 : 1;

        ILODMesh[] mainMeshes = existing.MainMeshPerLayer;
        bool mainStacked = false;
        try
        {
            int failedBefore = Failed;
            mainMeshes = StackMainMeshes(id.ToString(), existing.MainMeshPerLayer, single, span, direction, meshCache);

            // Only a complete stack retires the per-frame shaft; a LOD that fell back to the
            // single body still needs it.
            mainStacked = Failed == failedBefore;
        }
        catch (Exception exception)
        {
            if (Failed++ == 0)
            {
                logger.Exception?.LogException(exception);
            }
        }

        ILODMesh isolated;
        try
        {
            List<IMeshReference> lods = new List<IMeshReference>(BlueprintLods);
            for (int lod = 0; lod < BlueprintLods; lod++)
            {
                existing.IsolatedBlueprintMesh.TryGet(lod, out IMeshReference baseMesh);
                lods.Add(Stack(id.ToString(), lod, baseMesh, body, single, span, direction, meshCache) ?? baseMesh);
            }

            isolated = new RuntimeLODMesh(lods);
        }
        catch (Exception exception)
        {
            // Preview only. The building, its simulation and the save are untouched either way, so
            // the honest fallback is the stock two-layer preview rather than no preview.
            if (Failed++ == 0)
            {
                logger.Exception?.LogException(exception);
            }

            return existing;
        }

        ILODMesh combined = existing.CombinedBlueprintMesh;
        try
        {
            // GenerateEndCaps picks a pipe's (and wire's) stand by the connector's height -
            // `PipeStandsAndEndCap[max(0, io.Position_L.z)]`, an authored array as tall as vanilla's
            // pipes - so a stretched pipe's far end indexes past it and throws. Only this
            // mass-selection outline uses that lookup (placed pipes and the placement preview take
            // index 0), so a tall pipe keeps the stock outline rather than an exception per span.
            if (!ExceedsStands(connectors, theme))
            {
                combined = BuildingMeshGenerator.GenerateFullBlueprintMesh(
                    id.ToString(), isolated, connectors, theme, meshCache);
            }
        }
        catch (Exception exception)
        {
            // The isolated mesh is the one placement draws; a stale selection outline is not worth
            // losing it over.
            if (Failed++ == 0)
            {
                logger.Exception?.LogException(exception);
            }
        }

        Stacked++;
        if (mainStacked)
        {
            StaticallyStacked.Add(id);
        }

        // Rebuilt, not mutated, and the old instance is not disposed: every other field -
        // CustomDrawData above all, which Dispose tears down - is still the stock lift's.
        return new BuildingDrawData(
            existing.RenderVoidBelow,
            mainMeshes,
            isolated,
            combined,
            existing.PreviewMesh,
            existing.GlassMesh,
            existing.Colliders,
            existing.CustomDrawData,
            existing.HasCustomOverviewMesh,
            existing.CustomOverviewMesh,
            existing.SimulationRendererDrawsMainMesh);
    }

    private static bool ExceedsStands(IBuildingConnectorData connectors, VisualThemeBaseResources theme)
    {
        int pipeStands = theme?.PipeStandsAndEndCap?.Length ?? 0;
        foreach (BuildingFluidIO io in connectors.BuildingConnectorsOfType<BuildingFluidIO>())
        {
            if (io.Position_L.z >= pipeStands)
            {
                return true;
            }
        }

        return false;
    }

    public static void LogSummary(ILogger logger, string label)
    {
        logger.Info?.Log(
            "Extra Build Layers: stacked placement previews for " + Stacked + " tall " + label +
            " definition(s)" + (Failed > 0 ? "; " + Failed + " step(s) fell back to the two-layer preview." : "."));
        Stacked = 0;
        Failed = 0;
    }

    /// <summary>
    /// The building's own per-layer meshes, each made the full height of the shaft, so the chunk
    /// drawer draws the whole lift as one static mesh at every zoom level.
    ///
    /// This replaces drawing the extra bodies per frame from the simulation renderer, which had
    /// two faults. A simulation renderer only draws while <c>LOD.ShouldDrawDynamicBuildingSimulations</c>,
    /// so the shaft vanished at a distance. And it - like the chunk drawer - took the body from
    /// <c>MainMeshPerLayer[layer]</c>, where slots 1 and 2 are **empty** for anything copied from
    /// the stock lift: vanilla's two-layer lift can only start on floor 0, so the game authors one
    /// mesh and <c>ComputeMainMesh</c> leaves <c>LODEmptyMesh</c> above it, and
    /// <c>BuildingMeshLayerWidener</c> only fills the slots it adds. A tall lift can start on floor
    /// 1 or 2, and one placed there had no body at all. Every empty slot here takes the first real
    /// body instead.
    ///
    /// Stacked once per distinct body - the widened slots all share one - not once per slot.
    /// </summary>
    private static ILODMesh[] StackMainMeshes(
        string id, ILODMesh[] perLayer, ILODMesh single, int span, int direction, IMeshCache meshCache)
    {
        if (perLayer == null || perLayer.Length == 0)
        {
            return perLayer;
        }

        ILODMesh firstBody = null;
        foreach (ILODMesh mesh in perLayer)
        {
            if (mesh != null && mesh.Count > 0)
            {
                firstBody = mesh;
                break;
            }
        }

        if (firstBody == null)
        {
            return perLayer;
        }

        Dictionary<ILODMesh, ILODMesh> stackedByBody = new Dictionary<ILODMesh, ILODMesh>();
        ILODMesh[] result = new ILODMesh[perLayer.Length];
        for (int layer = 0; layer < perLayer.Length; layer++)
        {
            ILODMesh body = perLayer[layer] != null && perLayer[layer].Count > 0 ? perLayer[layer] : firstBody;
            if (!stackedByBody.TryGetValue(body, out ILODMesh stacked))
            {
                List<IMeshReference> lods = new List<IMeshReference>(MainLods);
                for (int lod = 0; lod < MainLods; lod++)
                {
                    if (!body.TryGet(lod, out IMeshReference baseMesh))
                    {
                        lods.Add(null);
                        continue;
                    }

                    IMeshReference built = null;
                    try
                    {
                        built = Stack(id, lod, baseMesh, body, single, span, direction, meshCache);
                    }
                    catch (Exception)
                    {
                        // Over 65k vertices at this LOD: keep the single body here rather than lose
                        // the LOD, and leave the per-frame shaft on for this definition.
                        Failed++;
                    }

                    lods.Add(built ?? baseMesh);
                }

                stacked = new RuntimeLODMesh(lods);
                stackedByBody[body] = stacked;
            }

            result[layer] = stacked;
        }

        return result;
    }

    /// <summary>
    /// One LOD of the stacked mesh: the stock blueprint (body and glass) where it was, then the
    /// shaft's extra bodies. Null when there is nothing to add at this LOD, so the caller keeps
    /// the stock mesh.
    /// </summary>
    private static IMeshReference Stack(
        string id, int lod, IMeshReference baseMesh, ILODMesh body, ILODMesh single, int span, int direction,
        IMeshCache meshCache)
    {
        using MeshBuilder builder = new MeshBuilder("ExtraBuildLayers.TallBlueprint(" + id + ")", lod);

        if (baseMesh != null && !baseMesh.IsEmpty)
        {
            builder.AddTranslate(baseMesh, float3.zero);
        }

        int bodies = TallShaft.ExtraBodies(span);
        if (body.TryGet(lod, out IMeshReference bodyMesh))
        {
            for (int k = 1; k <= bodies; k++)
            {
                builder.AddTranslate(bodyMesh, Up(TallShaft.BodyZ(k) * direction));
            }
        }

        if (TallShaft.NeedsCap(span) && single != null && single.TryGet(lod, out IMeshReference singleMesh))
        {
            builder.AddTranslate(singleMesh, Up(TallShaft.CapZ(span) * direction));
        }

        if (builder.Empty)
        {
            return null;
        }

        // One mesh, which is what the blueprint renderer draws. Twelve lift bodies are far under
        // 65k vertices; if a LOD ever is not, this throws and the caller falls back.
        TemporaryMeshReference mesh = builder.GenerateSingleMeshMax65KVertices();
        meshCache.Register(mesh);
        return mesh;
    }

    /// <summary>
    /// A building-local offset of <paramref name="layers"/> floors, in mesh space. One layer is one
    /// world unit - <c>SimulationRenderer.DrawMesh</c> turns <c>LocalVector(0, 0, z)</c> into
    /// <c>WorldVector(0, 0, z)</c> unscaled - and the cast to <c>float3</c> is the game's own
    /// Z-up to Y-up swap.
    /// </summary>
    private static float3 Up(int layers) => new WorldVector(0f, 0f, layers);
}
